// The docs seam: repo root in → list of documentation problems out.
// Checks that what the docs say (paths, npm scripts, ADR structure, the docs
// index) still matches the repository.
import fs from "node:fs";
import path from "node:path";

const SKIP_DIRS = new Set(["node_modules", ".next", ".git"]);
const KNOWN_EXT = /\.(md|json|ts|tsx|mjs|css|js|jsx|webp|png)$/;
const RESOLVE_EXT = [".ts", ".tsx", ".mjs", ".json", ".css", ".md"];
const ADR_STATUSES = ["已采纳", "提议中", "已被取代"];
const ADR_SECTIONS = ["背景", "决定", "后果"];
const IGNORE_RE = /<!--\s*docs-check-ignore:\s*(.*?)\s*-->/;
/* generated by the setup skill from templates; only required to be indexed */
const TOOL_OWNED = "docs/agents/";
const NPM_BUILTINS = new Set(["test", "start"]);

const read = (root, rel) => fs.readFileSync(path.join(root, rel), "utf8");
const isFile = (root, rel) => fs.existsSync(path.join(root, rel)) && fs.statSync(path.join(root, rel)).isFile();
const exists = (root, rel) => fs.existsSync(path.join(root, rel));

function walk(root, dir = "") {
  return fs.readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap((d) => {
    if (SKIP_DIRS.has(d.name)) return [];
    const rel = path.posix.join(dir, d.name);
    return d.isDirectory() ? walk(root, rel) : [rel];
  });
}

function topLevelDirs(root) {
  return new Set(
    fs.readdirSync(root, { withFileTypes: true })
      .filter((d) => d.isDirectory() && !SKIP_DIRS.has(d.name))
      .map((d) => d.name),
  );
}

/* the markdown files whose claims we verify */
function docFiles(root, files) {
  return files.filter(
    (f) => f === "README.md" || f === "CONTEXT.md" || (f.startsWith("docs/") && f.endsWith(".md")),
  );
}

/* inline `code` spans outside fenced blocks, with their line numbers and any ignore marker */
function* inlineSpans(text, report) {
  let fenced = false;
  let prevMarkerOnly = false;
  const lines = text.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*```/.test(line)) {
      fenced = !fenced;
      prevMarkerOnly = false;
      continue;
    }
    if (fenced) continue;
    const marker = line.match(IGNORE_RE);
    if (marker && !marker[1]) report(i + 1, "docs-check-ignore marker needs a reason");
    const exempt = Boolean(marker) || prevMarkerOnly;
    prevMarkerOnly = Boolean(marker) && line.replace(IGNORE_RE, "").trim() === "";
    if (exempt) continue;
    for (const m of line.matchAll(/`([^`\n]+)`/g)) yield { line: i + 1, span: m[1].trim() };
  }
}

/* "npm run x", "npm test" → the script name; anything else → null */
function npmScript(span) {
  const run = span.match(/^npm\s+run\s+([a-z][\w:-]*)/);
  if (run) return run[1];
  const builtin = span.match(/^npm\s+([a-z]+)\b/);
  return builtin && NPM_BUILTINS.has(builtin[1]) ? builtin[1] : null;
}

function pathProblem(span, ctx) {
  if (/\s/.test(span) || /^npm\b/.test(span) || span.includes("...")) return null;
  const token = span.replace(/^@\//, "").replace(/\/$/, "");
  const glob = /[*<>{}]/;

  if (token.includes("/")) {
    if (!ctx.topDirs.has(token.split("/")[0])) return null;
    const segments = token.split("/");
    const globAt = segments.findIndex((s) => glob.test(s));
    const hasGlob = globAt !== -1;
    const staticPart = (hasGlob ? segments.slice(0, globAt) : segments).join("/");
    const ok = hasGlob
      ? exists(ctx.root, staticPart)
      : exists(ctx.root, token) || RESOLVE_EXT.some((e) => isFile(ctx.root, token + e));
    return ok ? null : `\`${span}\` does not exist`;
  }
  if (KNOWN_EXT.test(token) && !glob.test(token) && !ctx.basenames.has(token)) {
    return `\`${span}\` does not exist anywhere in the repo`;
  }
  return null;
}

function checkSpans({ doc, text, ctx, problems }) {
  const report = (line, message) => problems.push({ file: doc, line, message });
  for (const { line, span } of inlineSpans(text, report)) {
    const script = npmScript(span);
    if (script) {
      ctx.mentioned.add(`${doc}:${script}`);
      if (!(script in ctx.scripts)) report(line, `\`${span}\`: no script "${script}" in package.json`);
      continue;
    }
    const message = pathProblem(span, ctx);
    if (message) report(line, message);
  }
}

function checkReadmeCoversScripts({ root, ctx, problems }) {
  if (!isFile(root, "README.md")) return;
  for (const name of Object.keys(ctx.scripts)) {
    if (!ctx.mentioned.has(`README.md:${name}`)) {
      problems.push({ file: "README.md", line: 1, message: `package.json script "${name}" is not documented in README.md` });
    }
  }
}

function checkAdrs({ root, files, problems }) {
  for (const file of files.filter((f) => /^docs\/adr\/[^/]+\.md$/.test(f))) {
    const add = (message) => problems.push({ file, line: 1, message });
    const name = path.posix.basename(file);
    const number = name.match(/^(\d{4})-[a-z0-9-]+\.md$/)?.[1];
    if (!number) {
      add("ADR file name must start with a four digit number, e.g. 0001-title.md (四位编号)");
      continue;
    }
    const text = read(root, file);
    const heading = text.match(/^# ADR-(\d{4})\b/m)?.[1];
    if (heading !== number) add(`heading must start with "# ADR-${number}" (found ${heading ? `ADR-${heading}` : "none"})`);
    if (!new RegExp(`^状态：(${ADR_STATUSES.join("|")})`, "m").test(text)) {
      add(`missing or invalid 状态 line — expected one of: ${ADR_STATUSES.join(" / ")}`);
    }
    for (const section of ADR_SECTIONS) {
      if (!new RegExp(`^## ${section}\\s*$`, "m").test(text)) add(`missing "## ${section}" section`);
    }
  }
}

function checkIndex({ root, files, problems }) {
  const index = "docs/README.md";
  if (!isFile(root, index)) {
    if (files.some((f) => f.startsWith("docs/"))) problems.push({ file: index, line: 1, message: "docs/README.md (the docs index) is missing" });
    return;
  }
  const text = read(root, index);
  const expected = [
    ...files.filter((f) => f.startsWith("docs/") && f.endsWith(".md") && f !== index).map((f) => f.slice("docs/".length)),
    ...(isFile(root, "CONTEXT.md") ? ["../CONTEXT.md"] : []),
  ];
  for (const target of expected) {
    if (!text.includes(target)) problems.push({ file: index, line: 1, message: `index does not list ${target}` });
  }
}

export function checkDocs({ root }) {
  const files = walk(root);
  const pkg = isFile(root, "package.json") ? JSON.parse(read(root, "package.json")) : {};
  const ctx = {
    root,
    scripts: pkg.scripts ?? {},
    topDirs: topLevelDirs(root),
    basenames: new Set(files.map((f) => path.posix.basename(f))),
    mentioned: new Set(),
  };
  const problems = [];
  for (const doc of docFiles(root, files).filter((d) => !d.startsWith(TOOL_OWNED))) {
    checkSpans({ doc, text: read(root, doc), ctx, problems });
  }
  checkReadmeCoversScripts({ root, ctx, problems });
  checkAdrs({ root, files, problems });
  checkIndex({ root, files, problems });
  return problems;
}
