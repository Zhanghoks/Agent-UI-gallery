// Renders the generated source files from a catalog. Not part of the tested
// seam — type-check and build cover it.
const HEADER = "// @generated by scripts/gen.mjs — do not edit. Run `npm run gen`.";
const j = (v) => JSON.stringify(v, null, 2);

const pascal = (id) => id.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

export function renderMeta({ entries, atoms }) {
  const internal = Object.fromEntries(atoms.map((a) => [a.id, { title: a.title, path: a.path }]));
  const meta = entries.map(({ css, order, ...rest }) => rest);
  return `${HEADER}
import type { Meta } from "./meta";

export const META: Meta[] = ${j(meta)};

export const INTERNAL: Record<string, { title: string; path: string }> = ${j(internal)};
`;
}

export function renderDemos({ entries }) {
  const imports = entries.map((e) => `import ${pascal(e.id)} from "@/components/gallery/${e.id}";`);
  const map = entries.map((e) => `  ${JSON.stringify(e.id)}: ${pascal(e.id)},`);
  return `"use client";

${HEADER}
import type { ComponentType } from "react";
${imports.join("\n")}

export const DEMOS: Record<string, ComponentType<{ variant?: string }>> = {
${map.join("\n")}
};
`;
}

export function renderCss({ cssImports }) {
  return `/* @generated by scripts/gen.mjs — do not edit. */\n${cssImports
    .map((p) => `@import "../${p}";`)
    .join("\n")}\n`;
}
